"""JACK 水下机器人 8 路推进器混控（SPI 通道 0-7 与电机 1-8 一一对应）。

布局来自 ~/桌面/JACK/urdf/JACK.urdf，机体坐标：X 前、Y 左、Z 上。
前排（X≈+0.445）：电机 1（左）、电机 6（右）。
中排（X≈+0.115）：电机 2（左）、电机 5（右）。
后排（X≈−0.415）：电机 3（左）、电机 4（右）。
水平推进器：电机 7（Y≈−0.605）、电机 8（Y≈+0.605）。

电机 1–6：推力沿 URDF +Z，负责 heave / pitch / roll（上浮下潜与姿态）。
电机 7–8：水平推进，负责 surge / yaw（前进后退与转向）。

★ 每电机物理方向校正 MOTOR_SIGN（2026-07-29 重测，覆盖 07-18 那次）：
   逐个 +12% 单独驱动实测——约定 +值应使 1-6 上浮、7-8 前进。
   结果：竖直 1/2 与右侧水平 7 方向正确(+1)；
         竖直 3/4/5/6 与左侧水平 8 装反(−1)，需取反。
   与 07-18 的差异只有 **电机 3**：那次记为 +1，本次实测为 −1（+12% 时下潜）。
   本次每一路都同时确认了"转的是不是那个位置"，通道↔电机映射无错位。
   仅作用于混控输出；网页"独立电机"测试模式绕过混控、保持原始方向不受影响。
"""

from __future__ import annotations

MOTOR_LABELS = (
    "1 前左·升沉Z",
    "2 中左·升沉Z",
    "3 后左·升沉Z",
    "4 后右·升沉Z",
    "5 中右·升沉Z",
    "6 前右·升沉Z",
    "7 水平·右",
    "8 水平·左",
)

# 每电机物理方向校正：+1 保持，−1 整体取反（该桨物理装反）。实测见模块 docstring。
MOTOR_SIGN = (1, 1, -1, -1, -1, -1, 1, -1)


def mix_thrusters(
    h: float,
    p: float,
    r: float,
    s: float,
    y: float,
    limit: float,
) -> list[int]:
    """将归一化指令 (-1~1) 混控为 8 路电机百分比 (-limit~limit)，并按 MOTOR_SIGN 校正物理方向。"""
    raw = [
        h - p + r,  # 电机 1 前左 · Z
        h + r,      # 电机 2 中左 · Z
        h + p + r,  # 电机 3 后左 · Z
        h + p - r,  # 电机 4 后右 · Z
        h - r,      # 电机 5 中右 · Z
        h - p - r,  # 电机 6 前右 · Z
        s - y,      # 电机 7 水平（Y 负侧）
        s + y,      # 电机 8 水平（Y 正侧）
    ]
    lim = float(limit)
    return [
        int(max(-lim, min(lim, sgn * v * lim)))
        for sgn, v in zip(MOTOR_SIGN, raw)
    ]
