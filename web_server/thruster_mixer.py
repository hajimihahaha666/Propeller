"""JACK 水下机器人 8 路推进器混控（SPI 通道 0-7 与电机 1-8 一一对应）。

机体坐标：X 前、Y 左、Z 上。**左/右一律指机身自身视角。**

★ 实际布局（2026-07-29 用户确认，**已与 JACK.urdf 不符，以本表为准**）：
    前排：电机 4（左）、电机 3（右）
    中排：电机 5（左）、电机 2（右）
    后排：电机 6（左）、电机 1（右）
    水平：电机 7（左）、电机 8（右）

  ⚠ 这与 urdf 里的原布局（前 1左/6右、中 2左/5右、后 3左/4右、水平 7在Y负侧/8在Y正侧）
    是**对角相反**的——整个编号相当于绕竖轴转了 180°。用户重装过电机（至少动过电机 3）。
    → 后果：混控里 pitch/roll/yaw 的分配项必须跟着搬位置，否则下 pitch 指令会推错那一排、
      机体往反方向倾，roll 也会左右颠倒。已于本次修正。
    → `MOTOR_SIGN` **不受影响**：它测的是"给正值这台桨往哪推"，与安装位置无关。

电机 1–6：推力沿 +Z，负责 heave / pitch / roll（上浮下潜与姿态）。
电机 7–8：水平推进，负责 surge / yaw（前进后退与转向）。

★ 每电机物理方向校正 MOTOR_SIGN（2026-07-29 重测，覆盖 07-18 那次）：
   逐个 +12% 单独驱动实测——约定 +值应使 1-6 上浮、7-8 前进。
   结果：竖直 1/2 与右侧水平 7 方向正确(+1)；
         竖直 3/4/5/6 与左侧水平 8 装反(−1)，需取反。
   与 07-18 的差异只有 **电机 3**：那次记为 +1，本次实测为 −1（+12% 时下潜）。
   本次每一路都同时确认了"转的是不是那个位置"，通道↔电机映射无错位。

   ★ 2026-07-29 起，网页"独立电机"模式**也会套 MOTOR_SIGN**（见 imu_web_server
     的 compute_channels_now），滑块正值统一表示「1-6 上浮 / 7-8 前进」。
     → 所以该模式**不再能用来测量** MOTOR_SIGN，它现在是**验证**工具：
       八路都给正值应当全部上浮/前进，哪一路不是就是那一路的符号记错了。
     → 要重新测量原始物理方向，得临时把这个 sign 关掉，或直接用
       `spi_send_burst.py`（它绕过整个网页服务，下发的就是原始通道值）。
"""

from __future__ import annotations

MOTOR_LABELS = (
    "1 后右·升沉Z",
    "2 中右·升沉Z",
    "3 前右·升沉Z",
    "4 前左·升沉Z",
    "5 中左·升沉Z",
    "6 后左·升沉Z",
    "7 水平·左",
    "8 水平·右",
)

# 每电机物理方向校正：+1 保持，−1 整体取反（该桨物理装反）。实测见模块 docstring。
MOTOR_SIGN = (1, 1, -1, -1, -1, -1, 1, -1)


def mix_thrusters(
    h: float,
    p: float,
    r: float,
    s: float,
    y: float,
    limit: float,
) -> list[int]:
    """将归一化指令 (-1~1) 混控为 8 路电机百分比 (-limit~limit)，并按 MOTOR_SIGN 校正物理方向。"""
    # 分配规则，由机体右手系 X前/Y左/Z上 的力矩 M = r×F = (y·F, −x·F, 0) 推出：
    #   roll  绕+X: Mx=+y·F   → r>0 需左列正、右列负      → 左列 +r / 右列 −r
    #   pitch 绕+Y: My=−x·F   → p>0 需后排正、前排负      → 前排 −p / 中排 0 / 后排 +p
    #   yaw   绕+Z: 左侧前推给出 Mz<0(右转)               → y>0(左转) 需左侧后推、右侧前推
    #                                                     → 水平左 s−y / 水平右 s+y
    # 与 UI 约定一致（index.html: A=yaw+ 左转、E=heave+ 上浮、W=surge+ 前进）；
    # 也与 imu_controller 的 PID 一致（out=pid(target−measured)，故 r>0 必须使实测 roll 增大）。
    raw = [
        h + p - r,  # 电机 1 后右 · Z
        h - r,      # 电机 2 中右 · Z
        h - p - r,  # 电机 3 前右 · Z
        h - p + r,  # 电机 4 前左 · Z
        h + r,      # 电机 5 中左 · Z
        h + p + r,  # 电机 6 后左 · Z
        s - y,      # 电机 7 水平·左
        s + y,      # 电机 8 水平·右
    ]
    lim = float(limit)
    return [
        int(max(-lim, min(lim, sgn * v * lim)))
        for sgn, v in zip(MOTOR_SIGN, raw)
    ]
